let currentQuestions = [];
let currentQuestion = 0;
let score = 0;
const questionEl = document.getElementById('question');
const choicesEl = document.getElementById('choices');
const nextBtn = document.getElementById('next-btn');
const scoreEl = document.getElementById('score');
const retryBtn = document.getElementById('retry-btn');

function toggleSidebar() {
    document.getElementById('sidebar').classList.toggle('active');
}

function shuffle(array) {
    for (let i = array.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [array[i], array[j]] = [array[j], array[i]];
    }
}

function startQuiz(dept) {
    switch(dept) {
        case 'CCS':
            currentQuestions = [...ccsQuestions];
            break;
        case 'CAS':
            currentQuestions = [...casQuestions];
            break;
        case 'CTE':
            currentQuestions = [...cteQuestions];
            break;
        case 'CBAA':
            currentQuestions = [...cbaaQuestions];
            break;
        case 'CCJE':
            currentQuestions = [...ccjeQuestions];
            break;
        case 'COF':
            currentQuestions = [...cofQuestions];
            break;
        case 'CFND':
            currentQuestions = [...cfndQuestions];
            break;
        case 'CHMT':
            currentQuestions = [...chmtQuestions];
            break;
    }

    if (currentQuestions.length === 0) {
        alert("No questions available for this department yet.");
        return;
    }

    shuffle(currentQuestions);
    currentQuestion = 0;
    score = 0;
    loadQuestion();
    toggleSidebar();
    retryBtn.style.display = 'none';
}

function loadQuestion() {
    const question = currentQuestions[currentQuestion];
    questionEl.textContent = question.question;
    choicesEl.innerHTML = '';
    question.choices.forEach((choice, index) => {
        const button = document.createElement('button');
        button.textContent = choice;
        button.classList.add('choice');
        button.addEventListener('click', () => selectChoice(index));
        choicesEl.appendChild(button);
    });
    nextBtn.style.display = 'none';
    scoreEl.textContent = '';
}

function selectChoice(index) {
    const buttons = choicesEl.getElementsByTagName('button');
    for (let button of buttons) {
        button.disabled = true;
        button.style.opacity = '0.5';
    }
    buttons[index].style.opacity = '1';
    if (index === currentQuestions[currentQuestion].correctAnswer) {
        buttons[index].style.backgroundColor = '#4CAF50';
        score++;
    } else {
        buttons[index].style.backgroundColor = '#f44336';
        buttons[currentQuestions[currentQuestion].correctAnswer].style.backgroundColor = '#4CAF50';
        buttons[currentQuestions[currentQuestion].correctAnswer].style.opacity = '1';
    }
    nextBtn.style.display = 'block';
}

nextBtn.addEventListener('click', () => {
    currentQuestion++;
    if (currentQuestion < currentQuestions.length) {
        loadQuestion();
    } else {
        showFinalScore();
    }
});

function showFinalScore() {
    questionEl.textContent = 'Quiz completed!';
    choicesEl.innerHTML = '';
    nextBtn.style.display = 'none';
    scoreEl.textContent = `Your score: ${score} out of ${currentQuestions.length}`;
    retryBtn.style.display = 'block';
}

retryBtn.addEventListener('click', () => {
    startQuiz(currentQuestions === ccsQuestions ? 'CCS' : 
              currentQuestions === casQuestions ? 'CAS' :
              currentQuestions === cteQuestions ? 'CTE' :
              currentQuestions === cbaaQuestions ? 'CBAA' :
              currentQuestions === ccjeQuestions ? 'CCJE' :
              currentQuestions === cofQuestions ? 'COF' :
              currentQuestions === cfndQuestions ? 'CFND' : 'CHMT');
});